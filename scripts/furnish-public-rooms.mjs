// Furnishes the public rooms with the AUTHENTIC classic-lounge furniture that
// already exists in the pack (classic1_* = the Welcome Lounge / "Antiguo
// Recibidor" set; classic2_* = the classic diner). "crl_" was a phantom prefix —
// Habbo's real classnames are classic1_..classic5_. Parses each model's heightmap
// and lays the furni out in clusters on valid floor tiles. Output: .tmp/furnish.sql
import fs from "fs";

// base item ids of placeable classic furni (skip floor/wall coverings)
const byName = {};
for (const line of fs.readFileSync(".tmp/classic.txt", "utf8").trim().split(/\n/)) {
  const [id, name] = line.split(/\t|\s+/);
  if (id && name && !/_floor|_wall|_block|_div|_gate/.test(name)) byName[name] = +id;
}
const pick = (...names) => names.map((n) => byName[n]).filter(Boolean);

// classic1 = Welcome Lounge, classic2 = diner. Repeat key pieces so rooms feel full.
const c1 = pick("classic1_sofa", "classic1_chair", "classic1_table1", "classic1_table2",
  "classic1_lamp", "classic1_plant", "classic1_pillar", "classic1_shelf", "classic1_desk");
const c2 = pick("classic2_counter", "classic2_drinkmach", "classic2_drinkmach2", "classic2_burger",
  "classic2_corner", "classic2_table", "classic2_chair", "classic2_stool", "classic2_plant");
const lounge = [...c1, c1[0], c1[1], c1[0], c1[1], c1[4], c1[5]]; // extra seating + decor

const ROOMS = {
  4: lounge.length ? lounge : c1,   // Recepción  -> Welcome Lounge
  5: c2.length ? c2 : c1,           // El Bar     -> diner
  6: c1,                            // Cine
  7: lounge.length ? lounge : c1,   // Salón Lounge
};

const models = {};
for (const line of fs.readFileSync(".tmp/models.tsv", "utf8").trim().split(/\n/)) {
  const [name, dx, dy, ...rest] = line.split("\t");
  models[name] = { dx: +dx, dy: +dy, heightmap: rest.join("\t") };
}
const ROOM_MODEL = { 4: "newbie_lobby", 5: "pub_a", 6: "cinema_a", 7: "dusty_lounge" };

function floorTiles(hm, dx, dy) {
  const rows = hm.split(/\\r|\r|\\n|\n/).filter((r) => r.length);
  const t = [];
  for (let y = 0; y < rows.length; y++)
    for (let x = 0; x < rows[y].length; x++) {
      const c = rows[y][x];
      if (c >= "0" && c <= "9" && !(Math.abs(x - dx) <= 1 && Math.abs(y - dy) <= 1)) t.push({ x, y, z: +c });
    }
  return t;
}

const out = ["-- Generated by scripts/furnish-public-rooms.mjs (authentic classic furni). Idempotent."];
out.push(`DELETE FROM items WHERE room_id IN (${Object.keys(ROOMS).join(",")});`);

for (const [roomId, furni] of Object.entries(ROOMS)) {
  const m = models[ROOM_MODEL[roomId]];
  if (!m || !furni.length) continue;
  const tiles = floorTiles(m.heightmap, m.dx, m.dy);
  // cluster: place on a sub-grid (every other tile) within the central open area
  const placed = tiles.filter((t, i) => (t.x % 2 === 0 && t.y % 2 === 0)).slice(0, 26);
  let n = 0;
  for (let i = 0; i < placed.length; i++) {
    const t = placed[i], item = furni[i % furni.length], rot = [2, 4, 0, 6][i % 4];
    out.push(`INSERT INTO items (user_id, room_id, item_id, x, y, z, rot, extra_data, wall_pos) VALUES (0, ${roomId}, ${item}, ${t.x}, ${t.y}, ${t.z.toFixed(6)}, ${rot}, '', '');`);
    n++;
  }
  console.log(`room ${roomId} (${ROOM_MODEL[roomId]}): placed ${n} classic furni`);
}
fs.writeFileSync(".tmp/furnish.sql", out.join("\n") + "\n");
console.log("SQL -> .tmp/furnish.sql");
