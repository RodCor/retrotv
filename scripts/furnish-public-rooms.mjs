// Furnishes the public rooms with furni that exist in the asset pack (the legacy
// public_items furniture, crl_*, isn't in a modern Nitro pack so the rooms render
// empty). Parses each model's heightmap, picks spaced valid floor tiles, and
// places a curated set. Outputs .tmp/furnish.sql (idempotent for the public rooms).
import fs from "fs";

const ROOMS = { 4: "newbie_lobby", 5: "pub_a", 6: "cinema_a", 7: "dusty_lounge" };
// base item ids that exist (plants, seating, bar, shelves, sound, throne)
const FURNI = [160, 163, 171, 28, 30, 28, 30, 127, 13, 2162, 230, 160, 171, 30, 28, 163];

const models = {};
for (const line of fs.readFileSync(".tmp/models.tsv", "utf8").trim().split(/\n/)) {
  const [name, dx, dy, ...rest] = line.split("\t");
  models[name] = { dx: +dx, dy: +dy, heightmap: rest.join("\t") };
}

function floorTiles(hm, dx, dy) {
  const rows = hm.split(/\\r|\r|\\n|\n/).filter((r) => r.length);
  const tiles = [];
  for (let y = 0; y < rows.length; y++) {
    for (let x = 0; x < rows[y].length; x++) {
      const c = rows[y][x];
      if (c >= "0" && c <= "9") {
        // skip the door tile + its immediate neighbours so the entrance stays clear
        if (Math.abs(x - dx) <= 1 && Math.abs(y - dy) <= 1) continue;
        tiles.push({ x, y, z: +c });
      }
    }
  }
  return tiles;
}

const out = ["-- Generated by scripts/furnish-public-rooms.mjs. Idempotent for rooms 4-7."];
out.push(`DELETE FROM items WHERE room_id IN (${Object.keys(ROOMS).join(",")});`);

for (const [roomId, model] of Object.entries(ROOMS)) {
  const m = models[model];
  if (!m) continue;
  const tiles = floorTiles(m.heightmap, m.dx, m.dy);
  if (!tiles.length) continue;
  // spread the furni across the room: pick evenly-spaced tiles
  const step = Math.max(1, Math.floor(tiles.length / (FURNI.length + 2)));
  let placed = 0;
  for (let i = 0; i < FURNI.length; i++) {
    const t = tiles[(i + 1) * step];
    if (!t) break;
    const rot = [0, 2, 4, 6][i % 4];
    out.push(
      `INSERT INTO items (user_id, room_id, item_id, x, y, z, rot, extra_data, wall_pos) ` +
      `VALUES (0, ${roomId}, ${FURNI[i]}, ${t.x}, ${t.y}, ${t.z.toFixed(6)}, ${rot}, '', '');`,
    );
    placed++;
  }
  console.log(`${model} (room ${roomId}): ${tiles.length} floor tiles, placed ${placed} furni`);
}

fs.writeFileSync(".tmp/furnish.sql", out.join("\n") + "\n");
console.log("SQL -> .tmp/furnish.sql");
